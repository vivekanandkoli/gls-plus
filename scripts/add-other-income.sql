-- Other Income & Expenses ledger (rental, consultant, etc.) — independent of
-- gold trading, tagged per book (official/unofficial). Net (income - expense)
-- per book is added on top of the WAC trading profit to get total profit.
-- Access is service-role only (RLS on, no policies), like gls.expenses.
create table if not exists gls.other_income (
  id          bigint generated by default as identity primary key,
  date        date not null default current_date,
  book        text not null check (book in ('official','unofficial')),
  kind        text not null check (kind in ('income','expense')),
  category    text not null,
  amount_thb  numeric(18,2) not null check (amount_thb >= 0),
  description text,
  created_by  integer references gls.users(id),
  created_at  timestamptz not null default now()
);

alter table gls.other_income enable row level security;

create index if not exists other_income_date_idx on gls.other_income (date desc);
create index if not exists other_income_book_idx on gls.other_income (book);
create index if not exists other_income_category_idx on gls.other_income (lower(category));
